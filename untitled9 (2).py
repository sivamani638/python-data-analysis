columns_to_drop = [col for col in ['math_score.1', 'math_score.2', 'math_score.3'] if col in df.columns]
df_clean = df.drop(columns=columns_to_drop)
display(df_clean.head())

"""### 2. Standardize Categorical Variables
Let's check unique values in `parental_education` and `extracurricular` and standardize them.
"""

print("Original Parental Education values:", df_clean['parental_education'].unique())
print("Original Extracurricular values:", df_clean['extracurricular'].unique())

def clean_education(val):
    if pd.isna(val):
        return val
    val_lower = str(val).strip().lower()
    if 'high school' in val_lower:
        return 'High School'
    elif 'bachelor' in val_lower:
        return 'Bachelors'
    elif 'master' in val_lower:
        return 'Masters'
    elif 'phd' in val_lower:
        return 'PhD'
    return val.strip().title()

df_clean['parental_education'] = df_clean['parental_education'].apply(clean_education)

def clean_extracurricular(val):
    if pd.isna(val):
        return val
    val_lower = str(val).strip().lower()
    if val_lower in ['y', 'yes', 'es']:
        return 'Yes'
    elif val_lower in ['n', 'no']:
        return 'No'
    return val.strip().title()

df_clean['extracurricular'] = df_clean['extracurricular'].apply(clean_extracurricular)

print("\nCleaned Parental Education values:", df_clean['parental_education'].unique())
print("Cleaned Extracurricular values:", df_clean['extracurricular'].unique())

"""### 3. Handle Missing Values
We will impute missing values:
- Numeric columns will be filled with their respective median values.
- Categorical columns will be filled with their mode (most frequent value).
- For the target variable `pass_final`, if there are missing values, we will drop those rows to keep model targets clean.
"""

df_clean = df_clean.dropna(subset=['pass_final'])

num_cols = df_clean.select_dtypes(include=[np.number]).columns
cat_cols = df_clean.select_dtypes(exclude=[np.number]).columns

for col in num_cols:
    median_val = df_clean[col].median()
    df_clean[col] = df_clean[col].fillna(median_val)

for col in cat_cols:
    if col != 'student_id':
        mode_val = df_clean[col].mode()[0]
        df_clean[col] = df_clean[col].fillna(mode_val)

print("Remaining missing values:")
print(df_clean.isnull().sum())
display(df_clean.head())

